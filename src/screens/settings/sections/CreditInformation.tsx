"use client";

import { Button } from "@/components/buttons";
import CardContent from "@/components/CardContent";
import Spinner from "@/components/Spinner";
import { auth } from "@/firebase/firebaseClient";
import { usePlatform } from "@/zustand/usePlatformStore";
import { cn } from "@/utils/tailwind";
import { formatNumber } from "@/utils/number";
import useProfileStore, { UsageMode } from "@/zustand/useProfileStore";
import { CircularProgress } from "@nextui-org/react";
import { useRouter } from "next/navigation";
import { useCallback, useMemo } from "react";

const CreditInformation = () => {
  const user = auth.currentUser;
  const { profile, isLoading, isDefaultData } = useProfileStore();
  const router = useRouter();
  const { isWeb } = usePlatform();

  const creditUsage = useMemo(
    () => profile.totalCredits - profile.credits,
    [profile.credits, profile.totalCredits]
  );

  const creditPercentage = useMemo(() => {
    return profile.totalCredits > 0
      ? (profile.credits / profile.totalCredits) * 100
      : 0;
  }, [profile.credits, profile.totalCredits]);

  const handleBuyClick = useCallback(() => {
    router.push("/payment-attempt");
  }, [router]);

  // Full literal class strings so Tailwind can statically detect and generate
  // them. Dynamic interpolation (e.g. `stroke-[${hex}]`) is NOT generated by
  // Tailwind and would leave the ring uncolored.
  const getColorClasses = (percentage: number) => {
    if (percentage >= 60)
      return {
        indicator: "stroke-[#24C69E]",
        track: "stroke-[#24C69E]/10",
      };
    if (percentage >= 40)
      return {
        indicator: "stroke-[#F6CC19]",
        track: "stroke-[#F6CC19]/10",
      };
    if (percentage >= 20)
      return {
        indicator: "stroke-[#F58B1A]",
        track: "stroke-[#F58B1A]/10",
      };
    return {
      indicator: "stroke-[#EA4227]",
      track: "stroke-[#EA4227]/10",
    };
  };

  const colorClasses = getColorClasses(creditPercentage);

  return (
    <CardContent
      title="Conversation Credits"
      isActive={profile.usageMode === UsageMode.Credits}
    >
      {isLoading || !user || isDefaultData ? (
        <Spinner />
      ) : (
        <div className="flex flex-col items-center justify-center">
          <CircularProgress
            aria-label="Credits remaining"
            classNames={{
              svg: "w-60 h-60 drop-shadow-md",
              indicator: cn("stroke-default", colorClasses.indicator),
              track: cn("stroke-default/10", colorClasses.track),
              value:
                "text-3xl font-semibold tabular-nums text-[#1E1F22] dark:text-white",
            }}
            value={creditPercentage}
            strokeWidth={4}
            showValueLabel={true}
            formatOptions={{
              style: "percent",
              minimumFractionDigits: 0,
              maximumFractionDigits: 2,
            }}
          />
          <p className="self-center text-center tabular-nums">
            {`${formatNumber(profile.credits)} of ${formatNumber(profile.totalCredits)} credits left`}
            <span className="block text-sm text-[#3B3B3B] dark:text-[#D8D8D8]">
              {`${formatNumber(creditUsage)} used`}
            </span>
          </p>
        </div>
      )}
      {isWeb && <Button onClick={handleBuyClick}>Buy 10,000 Credits</Button>}
    </CardContent>
  );
};

export default CreditInformation;
